#!/usr/bin/env python3
"""Test, build five AutoCAD targets and package the Windows installer."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile
from menu_package import build_classic_menu

ROOT = Path(__file__).resolve().parent
VERSION = '0.8.5'
TARGETS = {'2020': ('23.1.0', 'R23.1'), '2021': ('24.0.0', 'R24.0'),
           '2022': ('24.1.51000', 'R24.1'), '2023': ('24.2.0', 'R24.2'),
           '2024': ('24.3.0', 'R24.3')}

def run(*args, timeout=None):
    print('+ ' + ' '.join(map(str, args)), flush=True)
    subprocess.run(list(map(str, args)), cwd=ROOT, check=True, timeout=timeout)

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def package_xml(bundle):
    package = ET.Element('ApplicationPackage', SchemaVersion='1.0', AutodeskProduct='AutoCAD',
        Name='Профиля', AppVersion=VERSION, Description='Продольные и поперечные профили',
        Author='Sh0MeM0', ProductCode='{5A972638-EE7D-4BCD-92A7-03AC5C8CD184}',
        UpgradeCode='{25B26ECF-0C17-4968-BE99-4FC6E7F67A54}')
    ET.SubElement(package, 'CompanyDetails', Name='Sh0MeM0')
    # Like MDSTools, register a partial CUIX directly: a closed/absent ribbon
    # must never prevent the classic menu bar from loading our menu.
    menu = ET.SubElement(package, 'Components', Description='Classic menu')
    ET.SubElement(menu, 'RuntimeRequirements', OS='Win64', Platform='AutoCAD*',
                  SeriesMin='R23.1', SeriesMax='R24.3')
    ET.SubElement(menu, 'ComponentEntry', ComponentName='ProfilesClassicMenu',
                  ModuleName='./Contents/Profiles.cuix', LoadOnAutoCADStartup='True')
    for year, (_, series) in TARGETS.items():
        group = ET.SubElement(package, 'Components', Description='AutoCAD ' + year)
        ET.SubElement(group, 'RuntimeRequirements', OS='Win64', Platform='AutoCAD*',
                      SeriesMin=series, SeriesMax=series)
        entry = ET.SubElement(group, 'ComponentEntry', AppName='Profiles' + year, Version=VERSION,
            ModuleName='./Contents/' + year + '/Profiles.AutoCAD.dll',
            AppDescription='Профиля', LoadOnAutoCADStartup='True',
            LoadOnCommandInvocation='True', AppType='.Net')
        commands = ET.SubElement(entry, 'Commands', GroupName='SH0MEM0_PROFILES')
        for cmd in ('PROFILI', 'PROFILI_LONG', 'PROFILI_CROSS', 'PROFILI_MENU'):
            ET.SubElement(commands, 'Command', Global=cmd, Local=cmd)
    ET.indent(package)
    ET.ElementTree(package).write(bundle / 'PackageContents.xml', encoding='utf-8', xml_declaration=True)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dotnet', default=shutil.which('dotnet') or 'dotnet')
    parser.add_argument('--makensis', default=shutil.which('makensis') or 'makensis')
    args = parser.parse_args()
    artifacts = ROOT / 'artifacts'
    release = ROOT / 'releases'
    artifacts.mkdir(exist_ok=True)
    release.mkdir(exist_ok=True)
    run(sys.executable, '-m', 'unittest', 'discover', '-s', 'tests/packaging', '-v')
    run(args.dotnet, 'test', 'tests/Profiles.Core.Tests/Profiles.Core.Tests.csproj', '-c', 'Release',
        '--logger', 'trx;LogFileName=core-tests.trx', '--results-directory', artifacts / 'test-results')
    run(args.dotnet, 'build', 'tests/Profiles.UI.Regression/Profiles.UI.Regression.csproj', '-c', 'Release')
    ui_tests = ROOT / 'tests/Profiles.UI.Regression/bin/Release/net472/Profiles.UI.Regression.exe'
    if os.name == 'nt':
        run(ui_tests, timeout=180)
    else:
        run('xvfb-run', '-a', 'mono', ui_tests, timeout=180)
    bundle = artifacts / 'Sh0MeM0.Profiles.bundle'
    if bundle.exists():
        # Build staging is generated by this script, never the installed/user-data directory.
        shutil.rmtree(bundle)
    bundle.mkdir()
    for year, (api, _) in TARGETS.items():
        output = artifacts / 'bin' / year
        run(args.dotnet, 'build', 'src/Profiles.AutoCAD/Profiles.AutoCAD.csproj', '-c', 'Release',
            '-p:AcVersion=' + api, '--output', output, '--no-incremental')
        dest = bundle / 'Contents' / year
        dest.mkdir(parents=True)
        for name in ('Profiles.AutoCAD.dll', 'Profiles.Core.dll', 'Newtonsoft.Json.dll'):
            source = output / name
            if not source.is_file():
                raise RuntimeError('Required build output missing: ' + str(source))
            shutil.copy2(source, dest / name)
    build_classic_menu(bundle / 'Contents' / 'Profiles.cuix')
    package_xml(bundle)
    for source, name in ((ROOT / 'README.md', 'README.md'),
                         (ROOT / 'VALIDATION.md', 'VALIDATION.md'),
                         (ROOT.parent / 'LICENSE', 'LICENSE.txt'),
                         (ROOT / 'THIRD_PARTY_NOTICES.md', 'THIRD_PARTY_NOTICES.md'),
                         (ROOT / 'packaging/NSIS-COPYRIGHT.txt', 'NSIS-COPYRIGHT.txt')):
        shutil.copy2(source, bundle / name)
    for source in sorted(p for p in (ROOT / 'examples').iterdir() if p.suffix in {'.json', '.dxf'}):
        (bundle / 'Examples').mkdir(exist_ok=True)
        shutil.copy2(source, bundle / 'Examples' / source.name)
    for source in sorted((ROOT / 'docs').glob('*.png')):
        (bundle / 'docs').mkdir(exist_ok=True)
        shutil.copy2(source, bundle / 'docs' / source.name)
    files = sorted(p for p in bundle.rglob('*') if p.is_file())
    manifest = {str(p.relative_to(bundle)).replace(os.sep, '/'): sha(p) for p in files}
    (bundle / 'SHA256SUMS.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    files.append(bundle / 'SHA256SUMS.json')
    install_lines, uninstall_lines = [], []
    dirs = set()
    for source in files:
        relative = str(source.relative_to(bundle)).replace(os.sep, '\\')
        parent = str(source.parent.relative_to(bundle)).replace(os.sep, '\\')
        if parent != '.': dirs.add(parent)
        install_lines += ['SetOutPath "$INSTDIR' + ('\\' + parent if parent != '.' else '') + '"',
                          'File "' + str(source) + '"']
        uninstall_lines.append('Delete "$INSTDIR\\' + relative + '"')
    dirs.add('Contents')
    uninstall_lines += ['RMDir "$INSTDIR\\' + d + '"' for d in sorted(dirs, key=lambda d: (-d.count('\\'), d))]
    install = artifacts / 'install-files.nsh'
    uninstall = artifacts / 'uninstall-files.nsh'
    install.write_text('\n'.join(install_lines) + '\n', encoding='utf-8')
    uninstall.write_text('\n'.join(uninstall_lines) + '\n', encoding='utf-8')
    installer = release / ('Profiles-Setup-' + VERSION + '.exe')
    define = '/D' if os.name == 'nt' else '-D'
    run(args.makensis, '-V3' if os.name != 'nt' else '/V3',
        define + 'PAYLOAD=' + str(bundle), define + 'OUTPUT=' + str(installer),
        define + 'INSTALL_FILES=' + str(install), define + 'UNINSTALL_FILES=' + str(uninstall),
        ROOT / 'packaging' / 'installer.nsi')
    if installer.read_bytes()[:2] != b'MZ':
        raise RuntimeError('Installer is not a Windows executable')
    archive = release / ('Profiles-Bundle-' + VERSION + '.zip')
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        for source in sorted(bundle.rglob('*')):
            if source.is_file(): z.write(source, source.relative_to(bundle.parent))
    (release / 'SHA256SUMS.txt').write_text(''.join(sha(p) + '  ' + p.name + '\n'
        for p in (installer, archive)), encoding='ascii')
    print('Installer: ' + str(installer))

if __name__ == '__main__':
    main()
